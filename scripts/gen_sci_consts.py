#!/usr/bin/env python3
"""Generate Rust constants from the official Scintilla C header.

Only plain integer literals are translated.  Multi-token macro expressions
(such as ``SCI_START``-relative offsets) cannot be represented by a single
integer and are therefore skipped, because guessing their value would risk
emitting constants that disagree with the native library.

Usage:
    python3 scripts/gen_sci_consts.py
    python3 scripts/gen_sci_consts.py --input <Scintilla.h> --output <sci_consts.rs>
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_HEADER = REPO_ROOT / "vendor" / "scintilla-5.6.9" / "include" / "Scintilla.h"
DEFAULT_OUTPUT = REPO_ROOT / "crates" / "rnotepad-win" / "src" / "sci_consts.rs"

# Any `#define` that belongs to the constant families we translate.
CONST_DEFINE_PATTERN = re.compile(r"^\s*#\s*define\s+(?:SCI|SCN|SC)_[A-Za-z0-9_]+")

# A `#define` holding a single decimal or hexadecimal literal.  A trailing C
# comment is tolerated; macro expressions are rejected on purpose.
LITERAL_DEFINE_PATTERN = re.compile(
    r"^\s*#\s*define\s+(?P<name>(?:SCI|SCN|SC)_[A-Za-z0-9_]+)\s+"
    r"(?P<value>-?(?:0[xX][0-9a-fA-F]+|\d+))"
    r"\s*(?:/\*.*\*/|//.*)?$"
)

FILE_HEADER = """\
// Scintilla constants translated from the official C header.
//
// This file is generated by `scripts/gen_sci_consts.py` from
// `vendor/scintilla-5.6.9/include/Scintilla.h`.
// DO NOT EDIT BY HAND. Regenerate with:
//     python3 scripts/gen_sci_consts.py
"""


def parse_integer(literal: str) -> int:
    """Parse a C integer literal that contains no operators."""
    text = literal.strip()
    negative = text.startswith("-")
    unsigned = text[1:] if negative else text
    base = 16 if unsigned.lower().startswith("0x") else 10
    value = int(unsigned, base)
    return -value if negative else value


def as_i32(value: int) -> tuple[int, bool]:
    """Return the value as two's complement i32, plus whether it was wrapped."""
    if -(1 << 31) <= value <= (1 << 31) - 1:
        return value, False
    if 0 <= value <= 0xFFFF_FFFF:
        return value - (1 << 32), True
    raise ValueError(f"value {value} does not fit into 32 bits")


def collect_defines(header: Path) -> tuple[list[tuple[str, int]], list[tuple[str, int]]]:
    """Split numeric defines into unsigned (SCI/SCN) and signed (SC) groups."""
    unsigned: list[tuple[str, int]] = []
    signed: list[tuple[str, int]] = []
    skipped = 0

    for line in header.read_text(encoding="utf-8").splitlines():
        if CONST_DEFINE_PATTERN.match(line) is None:
            continue
        match = LITERAL_DEFINE_PATTERN.match(line)
        if match is None:
            skipped += 1
            continue
        name = match.group("name")
        value = parse_integer(match.group("value"))
        if name.startswith("SC_"):
            signed.append((name, value))
        else:
            unsigned.append((name, value))

    if skipped:
        print(
            f"warning: skipped {skipped} non-literal SCI/SCN/SC define(s)",
            file=sys.stderr,
        )
    return unsigned, signed


def render(unsigned: list[tuple[str, int]], signed: list[tuple[str, int]]) -> str:
    """Render the Rust module; names are sorted ordinally for reproducibility."""
    lines = [FILE_HEADER.rstrip("\n"), "", "#![allow(non_upper_case_globals)]", ""]

    lines.append("// Scintilla messages (iMessage values).")
    for name, value in sorted(unsigned, key=lambda item: item[0]):
        if not name.startswith("SCN_"):
            lines.append(f"pub const {name}: u32 = {value};")
    lines.append("")

    lines.append("// Scintilla notifications (WM_NOTIFY codes).")
    for name, value in sorted(unsigned, key=lambda item: item[0]):
        if name.startswith("SCN_"):
            lines.append(f"pub const {name}: u32 = {value};")
    lines.append("")

    lines.append("// Message parameters, styles and flags.")
    for name, value in sorted(signed, key=lambda item: item[0]):
        i32_value, wrapped = as_i32(value)
        comment = f" // 0x{value:08X}" if wrapped else ""
        lines.append(f"pub const {name}: i32 = {i32_value};{comment}")
    lines.append("")

    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input",
        type=Path,
        default=DEFAULT_HEADER,
        help=f"Scintilla.h to parse (default: {DEFAULT_HEADER})",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help=f"Rust file to write (default: {DEFAULT_OUTPUT})",
    )
    args = parser.parse_args()

    header: Path = args.input
    output: Path = args.output
    if not header.is_file():
        print(f"error: header not found: {header}", file=sys.stderr)
        return 1

    unsigned, signed = collect_defines(header)
    if not unsigned or not signed:
        print(f"error: no numeric defines found in {header}", file=sys.stderr)
        return 1

    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(render(unsigned, signed))

    print(f"wrote {len(unsigned) + len(signed)} constants to {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
